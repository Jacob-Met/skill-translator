import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {createCapture,appendCaptureMark} from '../src/capture.mjs';
import {reviseCaptureCalibration,exportCapture,reopenCapture} from '../src/capture-editing.mjs';
import {calibrationDraftRequest,receiveCalibrationDraft} from '../src/calibration-draft.mjs';
const base=new URL('./calibration-fixtures/',import.meta.url);
const native=JSON.parse(readFileSync(new URL('native-request.json',base)));
const report=JSON.parse(readFileSync(new URL('native-report.json',base)));
const corners=[{x:20,y:20},{x:170,y:25},{x:165,y:125},{x:25,y:120}];
let reference=createCapture(native.reference,corners,240,160);
reference=appendCaptureMark(reference,{sourcePx:{x:80,y:70},label:'Reference task point',kind:'fraction',toleranceMm:3});
const before=JSON.stringify(reference);
const declaration={stationaryPlane:true,basis:'Authored control: printed texture translates with the same flat workpiece.'};
const request=calibrationDraftRequest(reference,native.target,native.rois,declaration);
const draft=receiveCalibrationDraft(request,report);
assert.deepEqual(draft.corners,corners.map(p=>({x:p.x+7,y:p.y-5})));
assert.equal(draft.widthMm,240);assert.equal(draft.heightMm,160);
assert.equal(JSON.stringify(reference),before);assert.equal(draft.landmarks,undefined);
console.log('PASS exact transferred corners and dimensions; reference and task points unchanged');
let current=createCapture(native.target,corners,200,100);
current=appendCaptureMark(current,{sourcePx:{x:95,y:80},label:'Target mark',kind:'fraction',toleranceMm:2});
const revised=reviseCaptureCalibration(current,draft.corners,draft.widthMm,draft.heightMm,'Target');
revised.source.calibrationDraftEvidence=draft.evidence;
assert.deepEqual(revised.landmarks,current.landmarks);
const reopened=reopenCapture(exportCapture(revised),native.target);
assert.deepEqual(reopened.source.calibrationDraftEvidence,draft.evidence);
assert.deepEqual(reopened.landmarks,current.landmarks);
console.log('PASS existing Apply/edit/export/reopen retains target marks and source-bound proposal evidence');
for(const mutate of [r=>r.target.sha256='0'.repeat(64),r=>r.kernel.sha256='0'.repeat(64),r=>r.registration.settings.minScore=.1,r=>r.registration.rois[0][0]++,r=>r.registration.frames[0].stage=[1,0],r=>r.registration.frames[1].accepted=false,r=>r.registration.frames[1].stage=null,r=>r.registration.frames[1].matches[0].score=.2]){
  const altered=structuredClone(report);mutate(altered);assert.throws(()=>receiveCalibrationDraft(request,altered));
}
console.log('PASS changed source, kernel, settings, patches, reference offset and unresolved matching refuse');
assert.throws(()=>calibrationDraftRequest(reference,native.target,native.rois,{stationaryPlane:false,basis:'No'}));
assert.throws(()=>calibrationDraftRequest(reference,native.target,[[0,0,24,24],[2,2,24,24]],declaration));
assert.throws(()=>calibrationDraftRequest(reference,{...native.target,widthPx:193},native.rois,declaration));
const boundary=structuredClone(reference);boundary.source.corners=[{x:0,y:0},{x:191,y:0},{x:191,y:143},{x:0,y:143}];
assert.throws(()=>receiveCalibrationDraft(calibrationDraftRequest(boundary,native.target,native.rois,declaration),report));
console.log('PASS declarations, overlap, dimensions and translated corners outside target refuse');
const detached=calibrationDraftRequest(reference,native.target,native.rois,declaration);reference.source.corners[0].x=40;
assert.equal(detached.reference.source.corners[0].x,20);
draft.corners[0].x=99;assert.equal(draft.evidence.proposedCorners[0].x,27);
console.log('PASS asynchronous request and evidence snapshots are detached from mutable editors');
writeFileSync(new URL('reference-task.json',base),before);
console.log('5 draft groups passed');
